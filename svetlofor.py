color = input("Введіть колір світлофора (червоний, жовтий, зелений): ")

if color == "червоний":
    print("Cтій. Переходити дорогу заборонено")
elif color == "жовтий":
    print("Зачекай, Приготуйся до руху")
elif color == "зелений":
    print("Можна переходити дорогу")
else:
    print("Невідомий колір. Введіть: червоний, жовтий або зелений.")